"""
Lesson 1: Your first robot. No hardware, no downloads.

Run:  .venv/bin/python 01_get_a_robot/arm.py

What this does:
  1. Defines a 3-DoF arm from scratch in MuJoCo's XML format
  2. Lets it COLLAPSE under gravity  -> you see physics
  3. Holds it upright with a PD loop -> you see control
  4. Proves damping is what makes control possible
  5. Renders RGB + depth            -> you see what a VLA would see
  6. Writes a video + sensor images

The four bugs I hit while writing this are commented as [BUG n] so you can see
that getting a robot working is mostly debugging, and the bugs are informative.
"""
import os
import sys
import numpy as np
import mujoco
import imageio.v2 as imageio

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from robotics_utils import lookat, set_camera, camera_xml

OUT = os.path.join(os.path.dirname(__file__), "out")
os.makedirs(OUT, exist_ok=True)

KP, KD = 40.0, 4.0          # tuned below. Do not just crank these up.
TAU_MAX = 150.0
GOAL_Q = np.array([0.0, np.pi / 4, 0.0])

# ---------------------------------------------------------------------------
# 1. THE ROBOT. MJCF = MuJoCo's XML scene format. Isaac and PyBullet have
#    equivalents. This file literally IS the robot -- its mass, its geometry,
#    its torque limits. Read it and you know everything.
# ---------------------------------------------------------------------------
XML = """
<mujoco model="three_dof_arm">
  <option timestep="0.002" gravity="0 0 -9.81"/>

  <visual>
    <global offwidth="640" offheight="480"/>
    <quality shadowsize="4096"/>
  </visual>

  <worldbody>
    <light pos="0 0 3" dir="0 0 -1" diffuse="0.8 0.8 0.8"/>
    <light pos="1 -1 2" dir="0 0 -1" diffuse="0.3 0.3 0.3"/>

    <geom type="plane" size="2 2 0.1" rgba="0.85 0.85 0.88 1"/>

    <!-- the goal the end-effector should reach -->
    <site name="target" pos="0.35 0.30 0.45" size="0.025" rgba="0.1 0.9 0.3 1"/>

    <body name="base" pos="0 0 0.05">
      <geom type="cylinder" size="0.08 0.08 0.05" rgba="0.3 0.3 0.35 1"/>
      <body name="link1" pos="0 0 0.05">
        <!-- damping = friction in the joint. Every real joint has some.
             I left it out at first and the arm became uncontrollable. See [BUG 2]. -->
        <joint name="j1" type="hinge" axis="0 0 1" damping="1.0" range="-180 180"/>
        <geom type="capsule" fromto="0 0 0  0 0 0.3" size="0.04" rgba="0.2 0.5 0.9 1"/>
        <body name="link2" pos="0 0 0.3">
          <joint name="j2" type="hinge" axis="0 1 0" damping="1.0" range="-135 135"/>
          <geom type="capsule" fromto="0 0 0  0 0 0.25" size="0.035" rgba="0.2 0.7 0.5 1"/>
          <body name="link3" pos="0 0 0.25">
            <joint name="j3" type="hinge" axis="0 1 0" damping="1.0" range="-135 135"/>
            <geom type="capsule" fromto="0 0 0  0 0 0.2" size="0.03" rgba="0.9 0.6 0.1 1"/>
            <!-- site = a named point on the robot. This is the "hand". -->
            <site name="ee" pos="0 0 0.2" size="0.02" rgba="1 0.2 0.2 1"/>
          </body>
        </body>
      </body>
    </body>

    <!-- Cameras. A VLA sees exactly what these render.
         [BUG 5] Hand-writing xyaxes to aim a camera is a waste of your life.
         It is generated by robotics_utils.camera_xml() / lookat() instead. -->
    CAM_SIDE_XML
  </worldbody>

  <!-- 'motor' outputs raw torque proportional to ctrl. No position control built
       in. That's deliberate: you should see the control problem before it's solved. -->
  <actuator>
    <motor name="m1" joint="j1" gear="1" ctrlrange="-150 150"/>
    <motor name="m2" joint="j2" gear="1" ctrlrange="-150 150"/>
    <motor name="m3" joint="j3" gear="1" ctrlrange="-150 150"/>
  </actuator>
</mujoco>
"""

model = mujoco.MjModel.from_xml_string(
    XML.replace("CAM_SIDE_XML",
                camera_xml([1.7, -1.7, 0.95], [0, 0, 0.40], fovy=50, name="cam_side")))
data = mujoco.MjData(model)
EE_ID = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_SITE, "ee")
print(f"robot built: nu={model.nu} actuators, nq={model.nq} positions, "
      f"nv={model.nv} velocity dofs")


def ee_pos(d):
    """[BUG 1] site_xpos is DERIVED state -- it is only valid after mj_forward().
    Read it straight after mj_step() and you get zeros/stale values. This bites
    everyone. In sim: call mj_forward() before reading anything derived."""
    mujoco.mj_forward(model, d)
    return d.site_xpos[EE_ID].copy()


def show_state(d, tag):
    print(f"  {tag:26s} q={np.round(d.qpos[:], 3)}  "
          f"qd={np.round(d.qvel[:], 2)}  ee={np.round(ee_pos(d), 3)}")


def run_pd(steps, kp=KP, kd=KD, use_damping=True):
    """Run the PD loop. Returns peak speed and final error."""
    mujoco.mj_resetData(model, data)
    data.qpos[:] = [0.0, np.pi / 2, 0.0]
    peak = 0.0
    for _ in range(steps):
        tau = kp * (GOAL_Q - data.qpos[:]) - kd * data.qvel[:]
        if not use_damping:
            tau = kp * (GOAL_Q - data.qpos[:])   # no -kd*qvel term
        data.ctrl[:] = np.clip(tau, -TAU_MAX, TAU_MAX)
        mujoco.mj_step(model, data)
        peak = max(peak, np.abs(data.qvel[:]).max())
    return peak, np.abs(GOAL_Q - data.qpos[:])


# ---------------------------------------------------------------------------
# 2. PHYSICS. No control at all. Gravity wins.
# ---------------------------------------------------------------------------
print("\n--- PART A: physics, no control. gravity is not a suggestion. ---")
mujoco.mj_resetData(model, data)
data.qpos[:] = [0.0, np.pi / 2, 0.0]      # arm sticking straight out horizontally
show_state(data, "initial")
z0 = ee_pos(data)[2]
for _ in range(500):                      # 500 steps @ 2ms = 1.0 s
    mujoco.mj_step(model, data)
show_state(data, "after 1.0s, ctrl=0")
print(f"  -> end effector z: {z0:.3f} -> {ee_pos(data)[2]:.3f}   (fell to the floor)")
print("  -> This is the whole reason control exists. Gravity is a real force.")

# ---------------------------------------------------------------------------
# 3. CONTROL. PD, written longhand.
#      torque = kp * (target - current)  -  kd * velocity
#      kp = stiffness (how hard you pull toward the goal)
#      kd = damping   (how hard you brake)
# ---------------------------------------------------------------------------
print("\n--- PART B: identical robot, identical start, now with PD ---")
mujoco.mj_resetData(model, data)
data.qpos[:] = [0.0, np.pi / 2, 0.0]
show_state(data, "initial (same start)")
peak_damped, err_damped = run_pd(1500)    # 3.0 s at 1 kHz
show_state(data, "after 3.0s, PD")
print(f"  -> max joint error {err_damped.max():.5f} rad "
      f"({np.degrees(err_damped.max()):.2f} deg)")
print(f"  -> peak joint speed {peak_damped:.2f} rad/s, end effector stayed UP")

# ---------------------------------------------------------------------------
# 4. [BUG 2] GAIN TUNING. I first tried kp=100/200/300 expecting "stiffer=better".
#    Every single one was WORSE. Why: the torque limit saturates, so a big kp
#    doesn't mean a strong pull -- it means a chattering bang-bang controller.
# ---------------------------------------------------------------------------
print("\n--- PART C: why more gain is not better ---")
print("   kp    kd    max_err(deg)  peak_speed(rad/s)   verdict")
for kp, kd in [(10, 2), (20, 3), (40, 4), (80, 8), (150, 15), (300, 30)]:
    pk, er = run_pd(1500, kp=kp, kd=kd)
    verdict = "OK" if er.max() < 0.1 else ("sluggish" if er.max() < 0.5 else "UNSTABLE")
    print(f"  {kp:4} {kd:4}    {np.degrees(er.max()):8.2f}      {pk:8.2f}          {verdict}")

print("\n--- PART D: remove the damping term entirely (kd=0) ---")
pk_nod, er_nod = run_pd(1500, kd=0.0, use_damping=False)
pk_yes, er_yes = run_pd(1500, kd=4.0, use_damping=True)
print(f"  kd=0 (no -kd*qvel):  peak speed {pk_nod:8.2f} rad/s,  final err "
      f"{np.degrees(er_nod.max()):7.2f} deg")
print(f"  kd=4 (with damping): peak speed {pk_yes:8.2f} rad/s,  final err "
      f"{np.degrees(er_yes.max()):7.2f} deg")
# [BUG 6] I originally wrote np.degrees(a/b) here. a/b is a DIMENSIONLESS ratio,
# so converting it "to degrees" is meaningless -- it printed a bogus 57.6x.
# Ratios get no unit conversion. Only radians do.
print(f"  -> undamped peak speed is {pk_nod / max(pk_yes, 1e-9):.1f}x higher "
      f"(ratio is unitless)")
print(f"  -> and it rings at {pk_nod / max(pk_yes, 1e-9):.1f}x the frequency, "
      f"wasting actuator torque on oscillation instead of holding position.")
print("  -> Every real robot has damping. 'Gain tuning' is a genuine engineering skill,")
print("     and it is the thing that most often separates a demo from a product.")

# ---------------------------------------------------------------------------
# 5. SENSING. This is literally the tensor a VLA policy receives.
# ---------------------------------------------------------------------------
print("\n--- PART E: sensors (what the policy would see) ---")
mujoco.mj_resetData(model, data)
data.qpos[:] = [0.0, np.pi / 2, 0.0]
for _ in range(800):
    data.ctrl[:] = np.clip(KP * (GOAL_Q - data.qpos[:]) - KD * data.qvel[:],
                           -TAU_MAX, TAU_MAX)
    mujoco.mj_step(model, data)

renderer = mujoco.Renderer(model, height=240, width=320)
CAM = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_CAMERA, "cam_side")

# [BUG 3] I rendered before update_scene(), so the depth buffer held a single
# constant value (54.0 m everywhere) -- the depth buffer is only valid for the
# scene you actually pushed to the renderer. Order matters.
mujoco.mj_forward(model, data)
renderer.update_scene(data, camera=CAM)
rgb = renderer.render()

renderer.enable_depth_rendering()
renderer.update_scene(data, camera=CAM)     # <-- must re-push before depth
depth = renderer.render()
renderer.disable_depth_rendering()

print(f"  RGB   : shape={rgb.shape} dtype={rgb.dtype} min={rgb.min()} max={rgb.max()}")
print(f"  depth : shape={depth.shape} range=[{depth.min():.3f}, {depth.max():.3f}] m")
imageio.imwrite(os.path.join(OUT, "side_rgb.png"), rgb)
dnorm = (depth - depth.min()) / (depth.max() - depth.min() + 1e-9)
imageio.imwrite(os.path.join(OUT, "side_depth.png"), (255 * (1 - dnorm)).astype(np.uint8))
print("  -> depth is metric distance per pixel. In sim it's perfect = 'privileged")
print("     state'. Real depth sensors are noisy, sparse, and wrong at edges.")

# ---------------------------------------------------------------------------
# 6. VIDEO. [BUG 4] imageio needs the ffmpeg plugin for .mp4.
# ---------------------------------------------------------------------------
print("\n--- PART F: recording ---")
mujoco.mj_resetData(model, data)
data.qpos[:] = [0.0, np.pi / 2, 0.0]
renderer.update_scene(data, camera=CAM)
frames = [renderer.render()]
for i in range(1000):
    data.ctrl[:] = np.clip(KP * (GOAL_Q - data.qpos[:]) - KD * data.qvel[:],
                           -TAU_MAX, TAU_MAX)
    mujoco.mj_step(model, data)
    if i % 4 == 0:
        renderer.update_scene(data, camera=CAM)
        frames.append(renderer.render())
imageio.mimwrite(os.path.join(OUT, "arm_moves.mp4"), frames, fps=30)
print(f"  wrote {len(frames)} frames -> out/arm_moves.mp4")

print(f"\nDone. Artifacts in {OUT}/")